use super::*;

/// A pion v5.1.1 `replaydetector` testCase: one detector run's inputs and expected verdicts.
struct TestCase {
    name: &'static str,
    window_size: usize,
    max_seq: u64,
    input: Vec<u64>,
    valid: Vec<bool>,
    latest: Vec<bool>,
    expected: Vec<u64>,
}

impl TestCase {
    /// Mirrors pion's `runCheckCase`/`runCheckAccepterCase`: for every input, assert the check
    /// verdict, accept the packet (a no-op when the check failed), assert the `latest` return
    /// and finally the set of accepted sequence numbers.
    fn run(&self, det: &mut dyn ReplayDetector) {
        let mut out = vec![];
        for (i, &seq) in self.input.iter().enumerate() {
            let ok = det.check(seq);
            assert_eq!(
                ok, self.valid[i],
                "{}[{i}]: check({seq}) validity",
                self.name
            );
            if ok {
                out.push(seq);
            }
            // Accepting after a failed check must be inert (pion's nop closure).
            let latest = det.accept();
            assert_eq!(
                latest, self.latest[i],
                "{}[{i}]: accept({seq}) latest",
                self.name
            );
        }
        assert_eq!(
            out, self.expected,
            "{}: accepted sequence numbers",
            self.name
        );
    }
}

