/// pion's `TestReplayDetector`: the common cases plus the full-width sequence, through
/// `New` (the never-wrapping sliding window).
#[test]
fn test_replay_detector() {
    for tc in common_cases() {
        tc.run(&mut SlidingWindowDetector::new(tc.window_size, tc.max_seq));
    }

    // pion's FullWidthSequence: window 64 over the whole u64 range.
    TestCase {
        name: "FullWidthSequence",
        window_size: 64,
        max_seq: u64::MAX,
        input: vec![
            u64::MAX,
            u64::MAX - 1,
            u64::MAX - 64,
            u64::MAX - 63,
            u64::MAX - 1,
            u64::MAX,
        ],
        valid: vec![true, true, false, true, false, false],
        latest: vec![true, false, false, false, false, false],
        expected: vec![u64::MAX, u64::MAX - 1, u64::MAX - 63],
    }
    .run(&mut SlidingWindowDetector::new(64, u64::MAX));
}

