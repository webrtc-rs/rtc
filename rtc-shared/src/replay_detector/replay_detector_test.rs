/// Differential corpus recorded against pion/transport v5.1.1 `replaydetector`
/// (the throwaway Go generator is not committed). Each entry is one
/// `CheckSeq` + `Accept` call: bit 0 of the verdict is `Passed()`, bit 1 is
/// the `Accept` return value (whether the sequence became the latest). The
/// sequences exercise in-window steps, duplicates, beyond-window jumps,
/// beyond-`max_seq` probes and (for the wrapped corpus) the 0x0000/0xFFFF
/// wrap point.
#[test]
fn matches_pion_replay_detector() {
    let sliding = [(SLIDING_SEQS, SLIDING_VERDICTS)];
    for (seqs, verdicts) in sliding {
        let mut det = SlidingWindowDetector::new(64, 0x0000FFFFFFFFFFFF);
        for (i, &seq) in seqs.iter().enumerate() {
            let ok = det.check(seq);
            assert_eq!(
                ok,
                verdicts[i] & 1 != 0,
                "sliding[{i}]: check({seq:#x}) disagreed with pion"
            );
            let latest = det.accept();
            assert_eq!(
                latest,
                verdicts[i] & 2 != 0,
                "sliding[{i}]: accept({seq:#x}) latest disagreed with pion"
            );
        }
    }

    let wrapped = [(WRAPPED_SEQS, WRAPPED_VERDICTS)];
    for (seqs, verdicts) in wrapped {
        let mut det = WrappedSlidingWindowDetector::new(64, 0xFFFF);
        for (i, &seq) in seqs.iter().enumerate() {
            let ok = det.check(seq);
            assert_eq!(
                ok,
                verdicts[i] & 1 != 0,
                "wrapped[{i}]: check({seq:#x}) disagreed with pion"
            );
            let latest = det.accept();
            assert_eq!(
                latest,
                verdicts[i] & 2 != 0,
                "wrapped[{i}]: accept({seq:#x}) latest disagreed with pion"
            );
        }
    }
}
