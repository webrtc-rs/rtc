/// pion's `TestCheckSeqDoesNotCommit`: RFC 3711 3.3.2 — the replay list is updated only
/// after authentication, so a sequence number that passed a check but was never accepted
/// must still pass a later check.
#[test]
fn test_check_seq_does_not_commit() {
    // "New": the never-wrapping detector.
    let mut det = SlidingWindowDetector::new(16, 0xFFFF);
    assert!(det.check(5), "first check must pass");
    assert!(det.check(5), "re-check of an unaccepted seq must pass");
    det.accept();
    assert!(
        !det.check(5),
        "check after accept must reject the duplicate"
    );

    // "WithWrap": the wrapping detector.
    let mut det = WrappedSlidingWindowDetector::new(16, 0xFFFF);
    assert!(det.check(5), "first check must pass");
    assert!(det.check(5), "re-check of an unaccepted seq must pass");
    det.accept();
    assert!(
        !det.check(5),
        "check after accept must reject the duplicate"
    );
}

/// pion's `TestRejectedTokenIsInert`: accepting after a failed check (or with no check at
/// all) must not modify the window.
#[test]
fn test_rejected_token_is_inert() {
    // "New".
    let mut det = SlidingWindowDetector::new(16, 0xFFFF);
    assert!(!det.check(0x10000), "out-of-range seq must fail the check");
    assert!(!det.accept(), "accepting a rejected check must do nothing");
    assert!(
        !det.accept(),
        "accepting with no check at all must do nothing"
    );
    assert!(det.check(5), "window must be intact after inert accepts");
    det.accept();
    assert!(
        !det.check(5),
        "duplicate must still be rejected after inert accepts"
    );

    // "WithWrap".
    let mut det = WrappedSlidingWindowDetector::new(16, 0xFFFF);
    assert!(!det.check(0x10000), "out-of-range seq must fail the check");
    assert!(!det.accept(), "accepting a rejected check must do nothing");
    assert!(
        !det.accept(),
        "accepting with no check at all must do nothing"
    );
    assert!(det.check(5), "window must be intact after inert accepts");
    det.accept();
    assert!(
        !det.check(5),
        "duplicate must still be rejected after inert accepts"
    );
}
